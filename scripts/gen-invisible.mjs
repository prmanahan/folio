#!/usr/bin/env node
// Generates the "invisible-unicode strip set" for both sides from one source:
//   libs/site-core/ai/invisible_table.rs   (Rust, ai/types.rs)
//   frontend/src/lib/invisible-table.ts    (TypeScript)
//
// The set is every code point with the Unicode property
// Default_Ignorable_Code_Point, plus U+FFF9..=U+FFFB (interlinear annotation
// anchors). OWASP LLM Top 10 2026, LLM01 (#4711): these are invisible yet
// readable by a model, so they can carry hidden instructions.
//
// Node's bundled ICU data defines the property, so the table depends on the
// exact Node build that runs this. CI pins one in .node-version (a different
// Node or ICU build can differ). No dependencies.
//
// Usage: node scripts/gen-invisible.mjs           write both files
//        node scripts/gen-invisible.mjs --check   exit 1 if either file is stale

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const RUST_OUT = join(root, 'libs/site-core/ai/invisible_table.rs');
const TS_OUT = join(root, 'frontend/src/lib/invisible-table.ts');

const isDefaultIgnorable = (cp) =>
	/\p{Default_Ignorable_Code_Point}/u.test(String.fromCodePoint(cp)) ||
	(cp >= 0xfff9 && cp <= 0xfffb);

/** Sorted, merged inclusive [lo, hi] ranges. */
function computeRanges() {
	const ranges = [];
	for (let cp = 0; cp <= 0x10ffff; cp++) {
		// Surrogates are not scalar values; never present in a Rust `char`.
		if (cp >= 0xd800 && cp <= 0xdfff) continue;
		if (!isDefaultIgnorable(cp)) continue;
		const last = ranges[ranges.length - 1];
		if (last && last[1] === cp - 1) last[1] = cp;
		else ranges.push([cp, cp]);
	}
	return ranges;
}

const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
const unicode = process.versions.unicode;
const ranges = computeRanges();

const rust = `// GENERATED by scripts/gen-invisible.mjs, do not edit.
// Source: Unicode ${unicode}, property
// Default_Ignorable_Code_Point, plus U+FFF9..=U+FFFB, as shipped in the Node build
// pinned in .github/workflows/test.yml (a different Node or ICU build can differ).
// CI runs \`node scripts/gen-invisible.mjs --check\` (test.yml).

/// Sorted, non-overlapping, inclusive \`(lo, hi)\` code point ranges.
pub(super) const INVISIBLE_RANGES: &[(u32, u32)] = &[
${ranges.map(([lo, hi]) => `    (${hex(lo)}, ${hex(hi)}),`).join('\n')}
];
`;

const ts = `// GENERATED by scripts/gen-invisible.mjs, do not edit.
// Source: Unicode ${unicode}, property
// Default_Ignorable_Code_Point, plus U+FFF9..=U+FFFB, as shipped in the Node build
// pinned in .github/workflows/test.yml (a different Node or ICU build can differ).
// CI runs \`node scripts/gen-invisible.mjs --check\` (test.yml).

/** Sorted, non-overlapping, inclusive [lo, hi] code point ranges. */
export const INVISIBLE_RANGES: ReadonlyArray<readonly [number, number]> = [
${ranges.map(([lo, hi]) => `\t[${hex(lo)}, ${hex(hi)}],`).join('\n')}
];
`;

const outputs = [
	[RUST_OUT, rust],
	[TS_OUT, ts]
];

if (process.argv.includes('--check')) {
	let stale = false;
	for (const [path, want] of outputs) {
		let have = null;
		try {
			have = readFileSync(path, 'utf8');
		} catch {
			// missing file counts as stale
		}
		if (have !== want) {
			console.error(`STALE: ${path} differs from what gen-invisible.mjs generates`);
			stale = true;
		}
	}
	if (stale) process.exit(1);
	console.log(`OK: invisible tables match Unicode ${unicode} (${ranges.length} ranges)`);
} else {
	for (const [path, body] of outputs) writeFileSync(path, body);
	console.log(`wrote ${outputs.length} files, ${ranges.length} ranges, Unicode ${unicode}`);
}
